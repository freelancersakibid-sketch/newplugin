const { chromium } = require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:8080/wp-login.php');
 await page.locator('#user_login').fill('inventory-admin');await page.locator('#user_pass').fill('local-test-password');
 await Promise.all([page.waitForURL(/wp-admin/),page.locator('#wp-submit').click()]);
 await page.goto('http://localhost:8080/wp-admin/admin.php?page=vsr-stock-report');
 await page.locator('.vsr-wrap').waitFor();
 console.log('PASS: authenticated inventory page renders');
 const triggers=page.locator('[data-vsr-open-audit][data-item-id]:not([data-item-id="0"])');
 if(await triggers.count()<2)throw new Error('Need two audit items');
 const a=triggers.nth(0),b=triggers.nth(1);
 let first=true;
 await page.route('**/admin-ajax.php',async route=>{
  const data=new URLSearchParams(route.request().postData());
  if(data.get('action')==='vsr_get_audit_logs'&&first){first=false;await new Promise(r=>setTimeout(r,1000));}
  await route.continue();
 });
 await a.click();await page.locator('#vsr-audit-close').click();
 await b.click();await page.waitForTimeout(1800);
 const bid=await b.getAttribute('data-item-id');const owner=await b.getAttribute('data-owner-id');
 const rowTexts=await page.locator('#vsr-audit-tbody tr td:nth-child(2)').allTextContents();
 if(!rowTexts.length)throw new Error('Audit fixture rows missing');
 if(rowTexts.some(t=>!t.includes('#'+bid)&&!t.includes('Owner #'+owner)))throw new Error('Stale audit row rendered');
 console.log('PASS: delayed stale audit response discarded');
 await page.locator('#vsr-audit-close').click();
 await page.locator('[data-vsr-open-audit][data-item-id="0"]').click();
 await page.locator('#vsr-audit-type-filter').selectOption('restock');
 await page.waitForTimeout(400);
 const link=await page.locator('#vsr-audit-export-link').getAttribute('href');
 if(new URL(link).searchParams.get('change_type')!=='restock')throw new Error('CSV filter mismatch');
 const download=await Promise.all([page.waitForEvent('download'),page.locator('#vsr-audit-export-link').click()]);
 const file=await download[0].path();const fs=require('fs');const text=fs.readFileSync(file,'utf8');
 if(!text.includes('Movement Type'))throw new Error('Missing CSV header');
 const lines=text.trim().split('\n').slice(1);if(lines.length===0||lines.some(l=>!l.includes(',restock,')))throw new Error('Wrong movement type in CSV');
 console.log('PASS: real audit CSV download matches movement filter');
 await page.locator('#vsr-audit-close').click();
 await page.evaluate(()=>{document.querySelector('.vsr-table-scroll').scrollLeft=0;window.scrollTo(0,0)});
 const stockRow=page.locator('[data-vsr-row]').first();
 const stockInput=stockRow.locator('.vsr-qty-input');
 const nextStock=Number(await stockInput.inputValue())+1;
 await stockInput.fill(String(nextStock));
 const stockResponse=page.waitForResponse(r=>r.url().includes('admin-ajax.php')&&(r.request().postData()||'').includes('vsr_update_stock'));
 await stockRow.locator('[data-vsr-update]').click();
 const saved=await (await stockResponse).json();
 if(!saved.success||saved.data.new_stock!==nextStock)throw new Error('Browser exact stock save failed');
 console.log('PASS: browser exact stock form sends valid command and saves');
 await page.waitForTimeout(900);
 await page.evaluate(()=>{document.querySelector('.vsr-table-scroll').scrollLeft=0;window.scrollTo(0,0)});
 await page.screenshot({path:'/workspace/work/tests/dashboard-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const fits=await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth);
 if(!fits)throw new Error('Mobile page overflows viewport');
 await page.screenshot({path:'/workspace/work/tests/dashboard-mobile.png',fullPage:true});
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('PASS: desktop/mobile render without JavaScript exceptions');
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
